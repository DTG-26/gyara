CREATE OR REPLACE FUNCTION public.delete_user()
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  DELETE FROM auth.users WHERE id = auth.uid();
$$;

GRANT EXECUTE ON FUNCTION public.delete_user() TO authenticated;

CREATE OR REPLACE FUNCTION public.sync_artisan_rating()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  target_id bigint := COALESCE(NEW.artisan_id, OLD.artisan_id);
BEGIN
  UPDATE public.artisans
  SET rating = COALESCE((SELECT ROUND(AVG(rating)::numeric, 2) FROM public.reviews WHERE artisan_id = target_id), 0)
  WHERE id = target_id;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS on_review_changed ON public.reviews;
CREATE TRIGGER on_review_changed
  AFTER INSERT OR UPDATE OR DELETE ON public.reviews
  FOR EACH ROW EXECUTE FUNCTION public.sync_artisan_rating();

CREATE OR REPLACE FUNCTION public.sync_artisan_jobs()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  UPDATE public.artisans
  SET jobs = jobs + 1
  WHERE id = NEW.artisan_id;
  RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS on_hire_created ON public.hires;
CREATE TRIGGER on_hire_created
  AFTER INSERT ON public.hires
  FOR EACH ROW EXECUTE FUNCTION public.sync_artisan_jobs();
