CREATE TABLE IF NOT EXISTS profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  name text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS artisans (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  category text NOT NULL,
  location text NOT NULL,
  experience int NOT NULL DEFAULT 0,
  phone text NOT NULL DEFAULT '',
  whatsapp text NOT NULL DEFAULT '',
  rating numeric(5,2) NOT NULL DEFAULT 0,
  jobs int NOT NULL DEFAULT 0,
  initials text NOT NULL DEFAULT '',
  color text NOT NULL DEFAULT 'bg-blue-500',
  bio text NOT NULL DEFAULT '',
  availability text DEFAULT 'Available',
  pricing text,
  photo_url text,
  portfolio_photos text[] DEFAULT '{}',
  is_new boolean DEFAULT false,
  is_demo boolean DEFAULT false,
  is_verified boolean DEFAULT false,
  owner_customer_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reviews (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  artisan_id bigint NOT NULL REFERENCES artisans(id) ON DELETE CASCADE,
  reviewer_name text NOT NULL DEFAULT '',
  customer_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  is_verified_hire boolean DEFAULT false,
  rating int NOT NULL CHECK (rating BETWEEN 1 AND 5),
  comment text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS hires (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  artisan_id bigint NOT NULL REFERENCES artisans(id) ON DELETE CASCADE,
  customer_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  hired_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(artisan_id, customer_id)
);

CREATE TABLE IF NOT EXISTS saved_artisans (
  customer_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  artisan_id bigint NOT NULL REFERENCES artisans(id) ON DELETE CASCADE,
  PRIMARY KEY (customer_id, artisan_id)
);

