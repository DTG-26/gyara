-- Add email_verified column to profiles (safe to run multiple times)
ALTER TABLE profiles ADD COLUMN IF NOT EXISTS email_verified boolean NOT NULL DEFAULT false;

-- SECURITY DEFINER function so the anon key can mark a profile verified
-- (the API server validates the HMAC token before calling this)
CREATE OR REPLACE FUNCTION public.mark_email_verified(p_user_id uuid)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = public
AS $$
  UPDATE profiles SET email_verified = true WHERE id = p_user_id;
$$;

GRANT EXECUTE ON FUNCTION public.mark_email_verified(uuid) TO anon;

-- ============================
-- In-app messaging
-- ============================

CREATE TABLE IF NOT EXISTS messages (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  artisan_id bigint NOT NULL REFERENCES artisans(id) ON DELETE CASCADE,
  customer_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  sender_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  body text NOT NULL,
  read_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS messages_conversation_idx ON messages(artisan_id, customer_id, created_at);
CREATE INDEX IF NOT EXISTS messages_customer_idx ON messages(customer_id);

ALTER TABLE messages ENABLE ROW LEVEL SECURITY;

-- A message is visible to the customer in the conversation, or the owner of the artisan listing.
CREATE POLICY "messages_select" ON messages FOR SELECT USING (
  auth.uid() = customer_id
  OR auth.uid() IN (SELECT owner_customer_id FROM artisans WHERE id = artisan_id)
);

CREATE POLICY "messages_insert" ON messages FOR INSERT TO authenticated WITH CHECK (
  auth.uid() = sender_id
  AND (
    auth.uid() = customer_id
    OR auth.uid() IN (SELECT owner_customer_id FROM artisans WHERE id = artisan_id)
  )
);

-- Either participant can mark messages as read once they've viewed the thread.
CREATE POLICY "messages_update" ON messages FOR UPDATE USING (
  auth.uid() = customer_id
  OR auth.uid() IN (SELECT owner_customer_id FROM artisans WHERE id = artisan_id)
);

