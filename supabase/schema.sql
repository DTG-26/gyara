CREATE POLICY "artisans_select"    ON artisans FOR SELECT USING (true);
CREATE POLICY "artisans_insert"    ON artisans FOR INSERT TO authenticated WITH CHECK (auth.uid() = owner_customer_id);
CREATE POLICY "artisans_update"    ON artisans FOR UPDATE USING (auth.uid() = owner_customer_id);
CREATE POLICY "artisans_delete"    ON artisans FOR DELETE USING (auth.uid() = owner_customer_id);

CREATE POLICY "reviews_select"     ON reviews FOR SELECT USING (true);
CREATE POLICY "reviews_insert"     ON reviews FOR INSERT TO authenticated WITH CHECK (auth.uid() = customer_id);

CREATE POLICY "hires_select"       ON hires FOR SELECT USING (true);
CREATE POLICY "hires_insert"       ON hires FOR INSERT TO authenticated WITH CHECK (auth.uid() = customer_id);

CREATE POLICY "saved_artisans_all" ON saved_artisans USING (auth.uid() = customer_id) WITH CHECK (auth.uid() = customer_id);

-- ============================
-- Auto-create profile on signup
-- ============================

CREATE OR REPLACE FUNCTION handle_new_user()
RETURNS TRIGGER LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
  INSERT INTO public.profiles (id, name)
  VALUES (new.id, COALESCE(new.raw_user_meta_data->>'name', ''))
  ON CONFLICT (id) DO NOTHING;
  RETURN new;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION handle_new_user();

